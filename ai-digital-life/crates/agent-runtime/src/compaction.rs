use crate::token_counter::{
    TokenCounter, DEFAULT_TAIL_TURNS, PRUNE_MINIMUM, PRUNE_PROTECTED_TOOLS, TOOL_OUTPUT_MAX_CHARS,
};
use adl_kernel::types::conversation::{ConversationBlock, ConversationMessageRecord};

/// Result of a compaction operation.
#[derive(Debug, Clone)]
pub struct CompactionResult {
    /// Messages to keep (recent ones + protected).
    pub preserved: Vec<ConversationMessageRecord>,
    /// Messages that were pruned (only populated when `summary_needed` is true).
    pub pruned: Vec<ConversationMessageRecord>,
    /// Estimated token count of preserved messages.
    pub preserved_tokens: usize,
    /// Number of messages pruned.
    pub pruned_count: usize,
    /// Estimated token count of pruned messages.
    pub pruned_tokens: usize,
    /// Summary of pruned messages (to be generated by LLM).
    pub summary_needed: bool,
}

/// Compact a conversation by pruning old messages while preserving recent context.
///
/// Algorithm (matching OpenCode):
/// 1. If total tokens < PRUNE_MINIMUM, no compaction needed
/// 2. Preserve the last DEFAULT_TAIL_TURNS turns (user+assistant pairs)
/// 3. Preserve messages with protected tool outputs
/// 4. Prune remaining messages, replacing with a summary
///
/// Takes ownership of `messages` to avoid per-message clones on the hot path.
pub fn compact_messages(
    messages: Vec<ConversationMessageRecord>,
    provider: &str,
    counter: &TokenCounter,
) -> CompactionResult {
    let total_tokens: usize = messages.iter().map(|m| counter.count(&m.content, provider)).sum();

    if total_tokens < PRUNE_MINIMUM {
        return CompactionResult {
            preserved: messages,
            pruned: Vec::new(),
            preserved_tokens: total_tokens,
            pruned_count: 0,
            pruned_tokens: 0,
            summary_needed: false,
        };
    }

    // Single pass: decide preservation per message without HashSet allocation
    let tail_messages = DEFAULT_TAIL_TURNS * 2;
    let split_point = messages.len().saturating_sub(tail_messages);

    let mut preserved = Vec::with_capacity(tail_messages);
    let mut pruned = Vec::new();
    let mut preserved_tokens = 0usize;
    let mut pruned_tokens = 0usize;

    for (i, msg) in messages.into_iter().enumerate() {
        let msg_tokens = counter.count(&msg.content, provider);
        let should_preserve = i >= split_point || has_protected_tool_output(&msg);

        if should_preserve {
            preserved.push(msg);
            preserved_tokens += msg_tokens;
        } else {
            pruned.push(msg);
            pruned_tokens += msg_tokens;
        }
    }

    let pruned_count = pruned.len();

    CompactionResult {
        preserved,
        pruned,
        preserved_tokens,
        pruned_count,
        pruned_tokens,
        summary_needed: pruned_count > 0,
    }
}

/// Check if a message contains protected tool output.
fn has_protected_tool_output(msg: &ConversationMessageRecord) -> bool {
    for block in &msg.blocks {
        if let ConversationBlock::ToolCall { tool_name, .. } = block {
            if PRUNE_PROTECTED_TOOLS.contains(&tool_name.as_str()) {
                return true;
            }
        }
    }
    false
}

/// Truncate tool output to the maximum allowed chars.
pub fn truncate_tool_output(output: &str) -> String {
    if output.len() <= TOOL_OUTPUT_MAX_CHARS {
        output.to_string()
    } else {
        let truncated = &output[..TOOL_OUTPUT_MAX_CHARS];
        format!("{}\n... [truncated, {} chars total]", truncated, output.len())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::token_counter::PRUNE_PROTECT;
    use adl_kernel::create_id;
    use adl_kernel::types::conversation::ConversationRole;

    fn make_message(role: ConversationRole, content: &str) -> ConversationMessageRecord {
        ConversationMessageRecord {
            id: create_id("msg"),
            session_id: "sess".to_string(),
            run_id: None,
            role,
            content: content.to_string(),
            blocks: vec![],
            created_at: adl_kernel::now_ms(),
        }
    }

    #[test]
    fn no_compaction_below_threshold() {
        let counter = TokenCounter::new();
        let messages = vec![make_message(ConversationRole::User, "short message")];
        let result = compact_messages(messages, "openai", &counter);
        assert_eq!(result.pruned_count, 0);
        assert!(!result.summary_needed);
    }

    #[test]
    fn compaction_preserves_recent_turns() {
        let counter = TokenCounter::new();
        // Create enough messages to exceed PRUNE_PROTECT (40000 tokens)
        // Each CJK char ≈ 1 token, so 50000 chars
        let big_content = "你".repeat(50000);
        let messages: Vec<_> = (0..10)
            .map(|i| {
                make_message(
                    if i % 2 == 0 { ConversationRole::User } else { ConversationRole::Assistant },
                    &big_content,
                )
            })
            .collect();

        let result = compact_messages(messages, "openai", &counter);
        assert!(result.pruned_count > 0);
        assert!(result.summary_needed);
        // Should preserve last 4 messages (2 turns × 2 messages)
        assert!(result.preserved.len() <= 4);
    }

    #[test]
    fn truncate_long_output() {
        let long = "x".repeat(3000);
        let truncated = truncate_tool_output(&long);
        assert!(truncated.len() < long.len());
        assert!(truncated.contains("[truncated"));
    }

    #[test]
    fn truncate_short_output_unchanged() {
        let short = "short output";
        assert_eq!(truncate_tool_output(short), short);
    }

    #[test]
    fn compaction_triggers_at_prune_minimum() {
        let counter = TokenCounter::new();
        // PRUNE_MINIMUM = 20000, so ~25200 tokens should trigger compaction
        // With estimate_tokens, ~4 ASCII chars = 1 token
        // "hello world " = 12 chars, repeat(1400) = 16800 chars ≈ 4200 tokens per message
        // 6 messages × 4200 = 25200 tokens total (above PRUNE_MINIMUM, below PRUNE_PROTECT)
        let big_content = "hello world ".repeat(1400);
        let messages: Vec<_> = (0..6)
            .map(|i| {
                make_message(
                    if i % 2 == 0 { ConversationRole::User } else { ConversationRole::Assistant },
                    &big_content,
                )
            })
            .collect();

        let total: usize = messages.iter().map(|m| counter.count(&m.content, "openai")).sum();
        assert!(total >= PRUNE_MINIMUM, "total {} should exceed PRUNE_MINIMUM", total);
        assert!(
            total < PRUNE_PROTECT,
            "total {} should be below PRUNE_PROTECT for this test to be meaningful",
            total
        );

        let result = compact_messages(messages, "openai", &counter);
        assert!(result.summary_needed, "compaction should trigger when tokens >= PRUNE_MINIMUM");
        assert!(result.pruned_count > 0, "should have pruned some messages");
    }

    #[test]
    fn compaction_protects_recent_tokens() {
        let counter = TokenCounter::new();
        // Create messages exceeding PRUNE_PROTECT (40000 tokens)
        // CJK: each char ≈ 2 tokens, so 50000 chars ≈ 100000 tokens per message
        let big_content = "你".repeat(50000);
        let messages: Vec<_> = (0..10)
            .map(|i| {
                make_message(
                    if i % 2 == 0 { ConversationRole::User } else { ConversationRole::Assistant },
                    &big_content,
                )
            })
            .collect();

        let result = compact_messages(messages, "openai", &counter);
        // Should preserve tail turns (2 turns = 4 messages) + any protected messages
        assert!(
            result.preserved.len() <= 4,
            "should preserve only tail turns, got {}",
            result.preserved.len()
        );
    }
}
